// One-off script: extract representative color palette from each shiki bundled theme.
// Run: node scripts/extract-theme-palettes.cjs
// Outputs: src/components/ProseMirrorEditor/nodes/themePalettes.ts
const fs = require('fs')
const path = require('path')

const themesDir = path.join(process.cwd(), 'node_modules/@shikijs/themes/dist')
const files = fs.readdirSync(themesDir).filter(f => f.endsWith('.mjs') && !f.endsWith('.d.mts'))

const palettes = {}

for (const f of files) {
  const id = f.replace('.mjs', '')
  const content = fs.readFileSync(path.join(themesDir, f), 'utf-8')
  // The file is: export default Object.freeze(JSON.parse("..."))
  const m = content.match(/JSON\.parse\("([\s\S]+?)"\)\)/)
  if (!m) continue
  // The JSON string has escaped quotes
  const raw = m[1]
  // Unescape: \" → ", \\ → \
  const jsonStr = raw.replace(/\\"/g, '"').replace(/\\\\/g, '\\')
  let obj
  try {
    obj = JSON.parse(jsonStr)
  } catch (e) {
    console.error(`Failed to parse ${id}:`, e.message)
    continue
  }

  const colors = obj.colors || {}
  const tokenColors = obj.tokenColors || []

  const r = {
    bg: colors['editor.background'] || '',
    fg: colors['editor.foreground'] || '',
    keyword: '',
    string: '',
    func: '',
    comment: '',
  }

  for (const t of tokenColors) {
    const scopes = Array.isArray(t.scope) ? t.scope : [t.scope]
    const fg = t.settings && t.settings.foreground
    if (!fg) continue
    for (const sc of scopes) {
      if (typeof sc !== 'string') continue
      if (sc.includes('keyword') && !r.keyword) r.keyword = fg
      if (sc === 'string' && !r.string) r.string = fg
      if (sc.includes('comment') && !r.comment) r.comment = fg
      if (sc.includes('entity.name.function') && !r.func) r.func = fg
    }
  }

  // Fallback: if string not found, try broader match
  if (!r.string) {
    for (const t of tokenColors) {
      const scopes = Array.isArray(t.scope) ? t.scope : [t.scope]
      const fg = t.settings && t.settings.foreground
      if (!fg) continue
      for (const sc of scopes) {
        if (typeof sc !== 'string') continue
        if (sc.includes('string') && !r.string) { r.string = fg; break }
      }
      if (r.string) break
    }
  }

  palettes[id] = r
}

// Generate TypeScript
const ts = `// AUTO-GENERATED by scripts/extract-theme-palettes.cjs — do not edit manually.
// Representative color palette for each shiki bundled theme.
// Extracted from @shikijs/themes tokenColors + editor colors.
// Used by settings dropdown to show color swatches per theme.

export interface ThemePalette {
  bg: string
  fg: string
  keyword: string
  string: string
  func: string
  comment: string
}

export const THEME_PALETTES: Readonly<Record<string, ThemePalette>> = ${JSON.stringify(palettes, null, 2)}
`

const outPath = path.join(process.cwd(), 'src/components/ProseMirrorEditor/nodes/themePalettes.ts')
fs.writeFileSync(outPath, ts)
console.log(`Written ${Object.keys(palettes).length} theme palettes to ${outPath}`)
